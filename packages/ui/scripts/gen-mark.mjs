// Generates src/press/mark.ts from design/prototype/samite-mark.js (the owner's mark as one SVG path).
// Run: pnpm --filter @samite/ui gen:mark
import { readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { dirname, resolve } from "node:path"

const here = dirname(fileURLToPath(import.meta.url))
const src = readFileSync(resolve(here, "../../../design/prototype/samite-mark.js"), "utf8")
const vb = src.match(/vb:\s*\[([^\]]+)\]/)?.[1]
const d = src.match(/d:\s*'([^']+)'/)?.[1]
if (!vb || !d) throw new Error("could not find vb/d in samite-mark.js")

const out = `// GENERATED by scripts/gen-mark.mjs from design/prototype/samite-mark.js. Do not edit by hand.
// The Samite mark (eye in a spiky sun) as path data. Same shape as brand/samite-mark-*.svg. Fill with evenodd.

export const SAMITE_MARK = {
  vb: [${vb.split(",").map((s) => s.trim()).join(", ")}] as const,
  d: ${JSON.stringify(d)},
}

/** Width / height of the mark's viewBox (≈ 1.2716). */
export const MARK_ASPECT = SAMITE_MARK.vb[2] / SAMITE_MARK.vb[3]

let path: Path2D | null = null

/** Draws the mark with its top-left at (x, y), h px tall. Returns the drawn width. */
export function drawSamiteMark(ctx: CanvasRenderingContext2D, x: number, y: number, h: number): number {
  const m = SAMITE_MARK,
    s = h / m.vb[3]
  ctx.save()
  ctx.translate(x - m.vb[0] * s, y - m.vb[1] * s)
  ctx.scale(s, s)
  ctx.fill((path ??= new Path2D(m.d)), "evenodd")
  ctx.restore()
  return m.vb[2] * s
}
`
writeFileSync(resolve(here, "../src/press/mark.ts"), out)
console.log("mark.ts written, path length", d.length)
